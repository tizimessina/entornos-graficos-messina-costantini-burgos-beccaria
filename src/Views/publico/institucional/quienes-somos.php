<h1>Quiénes somos</h1>

<p class="ae-entrada">
    AeroEB es un punto único para buscar, comparar y reservar vuelos de varias
    aerolíneas, sin tener que entrar al sitio de cada una.
</p>

<section class="ae-panel mt-4" aria-labelledby="titulo-que-hacemos">
    <h2 id="titulo-que-hacemos" class="h5 mt-0">Qué hacemos</h2>
    <p>
        AeroEB no opera vuelos propios: es un intermediario entre las aerolíneas
        adheridas y los pasajeros. Cada aerolínea carga y administra su propia oferta
        (vuelos, horarios, precios y promociones) y el pasajero la compara con la de
        las demás en un mismo listado.
    </p>
    <p class="mb-0">
        Para que la información sea confiable, la administración de AeroEB autoriza
        cada cuenta de aerolínea antes de que pueda publicar, y revisa cada promoción
        antes de que se muestre en el sitio.
    </p>
</section>

<section class="ae-panel mt-4" aria-labelledby="titulo-mision">
    <h2 id="titulo-mision" class="h5 mt-0">Misión</h2>
    <p>
        Que cualquier persona pueda buscar, comparar y reservar pasajes de varias
        aerolíneas desde un solo lugar, de forma accesible y sin trámites de más.
    </p>

    <h2 class="h5">Visión</h2>
    <p>
        Ser el punto de consulta de referencia para comparar la oferta aérea, con
        información confiable y un sitio que pueda usar todo el mundo.
    </p>

    <h2 class="h5">Objetivos</h2>
    <ul class="mb-0">
        <li>Comparar vuelos de distintas aerolíneas para una misma ruta en pocos clics.</li>
        <li>Que el sitio se pueda usar con cualquier dispositivo y con tecnologías de apoyo.</li>
        <li>Que cada aerolínea administre su propia oferta, con promociones revisadas antes de publicarse.</li>
        <li>Confirmar cada operación en pantalla y por correo.</li>
    </ul>
</section>

