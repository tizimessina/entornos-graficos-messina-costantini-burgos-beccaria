<h1>Política de privacidad</h1>

<p class="ae-entrada">
    Guardamos solo los datos que hacen falta para que puedas reservar, y no los
    vendemos ni los cedemos a nadie.
</p>

<div class="ae-panel mt-4">
    <section class="mb-4">
        <h2 class="h5 mt-0">Qué datos guardamos</h2>
        <ul class="mb-0">
            <li>Los de tu cuenta: nombre, apellido, correo electrónico y, si lo cargás, teléfono.</li>
            <li>Tu contraseña, pero nunca en texto plano: se guarda cifrada con un algoritmo de
                un solo sentido (bcrypt), así que ni la administración puede leerla.</li>
            <li>Tus reservas: vuelo, cantidad de asientos, importe, estado y fechas.</li>
            <li>Si nos escribís por el formulario de contacto: tu nombre, tu correo, el mensaje y la
                dirección IP desde la que lo enviaste.</li>
        </ul>
    </section>

    <section class="mb-4">
        <h2 class="h5">Para qué los usamos</h2>
        <ul class="mb-0">
            <li>Para validar tu cuenta y dejarte iniciar sesión.</li>
            <li>Para mandarte el comprobante de pago y los avisos sobre tus reservas
                (por ejemplo, si la aerolínea cancela el vuelo).</li>
            <li>Para mandarte las novedades del sitio, solo si lo elegiste en Mi cuenta. Lo podés
                desactivar cuando quieras.</li>
            <li>Para responder tu consulta de contacto.</li>
        </ul>
    </section>

    <section class="mb-4">
        <h2 class="h5">Con quién los compartimos</h2>
        <p class="mb-0">
            Con nadie. Las aerolíneas ven en su panel cifras de ocupación y ventas de sus vuelos,
            pero no la lista de pasajeros ni sus datos de contacto. Los avisos a los pasajeros los
            envía AeroEB.
        </p>
    </section>

    <section class="mb-4">
        <h2 class="h5">Cookies</h2>
        <p class="mb-0">
            Usamos una sola cookie, la de la sesión, que hace falta para mantenerte conectado
            mientras navegás. No usamos cookies de publicidad ni de seguimiento.
        </p>
    </section>

    <section>
        <h2 class="h5">Tus derechos</h2>
        <p class="mb-0">
            Podés ver y corregir tus datos en <a href="/mi-cuenta">Mi cuenta</a>. Para pedir que
            borremos tu cuenta, escribinos desde el <a href="/contacto">formulario de contacto</a>.
        </p>
    </section>
</div>
