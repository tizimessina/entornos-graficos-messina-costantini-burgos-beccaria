<h1>Términos y condiciones</h1>

<p class="ae-entrada">
    Al usar AeroEB aceptás estas reglas. Son las mismas que aplica el sitio
    al reservar, pagar y cancelar.
</p>

<div class="ae-panel mt-4">
    <section class="mb-4">
        <h2 class="h5 mt-0">1. Qué es AeroEB</h2>
        <p class="mb-0">
            AeroEB es una plataforma académica que reúne la oferta de aerolíneas adheridas.
            No opera vuelos ni procesa pagos reales: el pago es una simulación y los vuelos,
            aerolíneas y precios publicados son de prueba.
        </p>
    </section>

    <section class="mb-4">
        <h2 class="h5">2. Cuentas</h2>
        <ul class="mb-0">
            <li>Para reservar hace falta una cuenta de pasajero con el correo validado.</li>
            <li>Las cuentas de aerolínea quedan pendientes hasta que la administración las autoriza.</li>
            <li>Sos responsable de mantener en secreto tu contraseña. Después de 5 intentos fallidos
                seguidos el ingreso se bloquea durante 15 minutos.</li>
            <li>La administración puede suspender una cuenta que haga un uso indebido del sitio.</li>
        </ul>
    </section>

    <section class="mb-4">
        <h2 class="h5">3. Reservas y pago</h2>
        <ul class="mb-0">
            <li>Se pueden reservar hasta 9 asientos por operación, según la disponibilidad del vuelo.</li>
            <li>La reserva queda pendiente de pago durante 24 horas. Si no se paga en ese plazo,
                se cancela sola y los asientos se liberan.</li>
            <li>Al confirmar el pago la reserva pasa a confirmada y enviamos el comprobante por correo.</li>
        </ul>
    </section>

    <section class="mb-4">
        <h2 class="h5">4. Promociones</h2>
        <ul class="mb-0">
            <li>Las proponen las aerolíneas y solo se publican si la administración las aprueba.</li>
            <li>Cada aerolínea tiene como máximo una promoción vigente a la vez.</li>
            <li>Un código vale solo para vuelos de la aerolínea que lo emitió y dentro de sus fechas de vigencia.</li>
        </ul>
    </section>

    <section class="mb-4">
        <h2 class="h5">5. Cancelaciones</h2>
        <ul class="mb-0">
            <li>Una reserva pendiente de pago se puede cancelar en cualquier momento.</li>
            <li>Una reserva confirmada se puede cancelar hasta 72 horas antes de la salida del vuelo.</li>
            <li>Si la aerolínea cancela un vuelo, se cancelan todas sus reservas y se avisa por correo
                a los pasajeros.</li>
        </ul>
    </section>

    <section>
        <h2 class="h5">6. Contacto</h2>
        <p class="mb-0">
            Cualquier consulta sobre estas condiciones, escribinos desde el
            <a href="/contacto">formulario de contacto</a>.
        </p>
    </section>
</div>
