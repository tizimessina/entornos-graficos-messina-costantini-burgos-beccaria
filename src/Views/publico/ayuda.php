        <section class="ae-panel h-100" aria-labelledby="titulo-ayuda-reservar">
            <h2 id="titulo-ayuda-reservar" class="h5 mt-0">Reservar un vuelo</h2>
            <ol class="mb-0">
                <li>Buscá el vuelo desde la portada o desde <a href="/vuelos">Vuelos</a>, con origen,
                    destino, fechas y cantidad de pasajeros.</li>
                <li>Achicá la lista con los filtros de precio, horario y aerolínea, y ordenala como prefieras.</li>
                <li>Entrá al detalle del vuelo y tocá «Reservar este vuelo». Si no iniciaste sesión, te la
                    pedimos en ese momento.</li>
                <li>Elegí la cantidad de asientos y, si tenés, ingresá un código de promoción.</li>
                <li>Confirmá el pago dentro de las 24 horas. Te mandamos el comprobante por correo.</li>
            </ol>
        </section>
    </div>

