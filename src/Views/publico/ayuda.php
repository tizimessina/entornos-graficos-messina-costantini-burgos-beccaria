<h1>Ayuda</h1>

<p class="ae-entrada">
    Cómo se usa AeroEB, paso por paso. Si te queda alguna duda, mirá las
    <a href="/institucional/preguntas-frecuentes">preguntas frecuentes</a>.
</p>

<div class="row g-4 mt-1">
    <div class="col-12 col-lg-6">
        <section class="ae-panel h-100" aria-labelledby="titulo-ayuda-reservar">
            <h2 id="titulo-ayuda-reservar" class="h5 mt-0">Reservar un vuelo</h2>
            <ol class="mb-0">
                <li>Buscá el vuelo desde la portada o desde <a href="/vuelos">Vuelos</a>, con origen,
                    destino, fechas y cantidad de pasajeros.</li>
                <li>Achicá la lista con los filtros de precio, horario y aerolínea, y ordenala como prefieras.</li>
                <li>Entrá al detalle del vuelo y tocá «Reservar este vuelo». Si no iniciaste sesión, te la
                    pedimos en ese momento.</li>
                <li>Elegí la cantidad de asientos y, si tenés, ingresá un código de promoción.</li>
                <li>Confirmá el pago dentro de las 24 horas. Te mandamos el comprobante por correo.</li>
            </ol>
        </section>
    </div>

    <div class="col-12 col-lg-6">
        <section class="ae-panel h-100" aria-labelledby="titulo-ayuda-cuenta">
            <h2 id="titulo-ayuda-cuenta" class="h5 mt-0">Tu cuenta</h2>
            <ul class="mb-0">
                <li><a href="/registro">Creá una cuenta</a> y abrí el enlace que te mandamos por correo
                    para activarla.</li>
                <li>En <a href="/mi-cuenta">Mi cuenta</a> cambiás tus datos, tu contraseña y si querés
                    recibir las novedades por correo.</li>
                <li>En <a href="/mi-cuenta/reservas">Mis reservas</a> ves el estado de cada reserva, la
                    pagás, la cancelás o imprimís el comprobante.</li>
                <li>¿Te olvidaste la contraseña? Pedí una nueva desde <a href="/recuperar">Recuperar contraseña</a>.</li>
            </ul>
        </section>
    </div>
</div>

<section class="ae-panel mt-4" aria-labelledby="titulo-glosario">
    <h2 id="titulo-glosario" class="h5 mt-0">Glosario</h2>
    <dl class="ae-ficha mb-0">
        <dt>Localizador</dt>
        <dd>Código de seis letras y números que identifica tu reserva, por ejemplo H4RT9B.</dd>

        <dt>Código IATA</dt>
        <dd>Código de tres letras que identifica a cada aerolínea, por ejemplo AND.</dd>

        <dt>Código de promoción</dt>
        <dd>Palabra que se ingresa al reservar para obtener el descuento de la aerolínea, por ejemplo VERANO26.</dd>

        <dt>Reserva pendiente de pago</dt>
        <dd>Reserva que guarda tus asientos durante 24 horas mientras no la pagues.</dd>

        <dt>Reserva confirmada</dt>
        <dd>Reserva ya pagada. Es una compra y aparece en Mis compras.</dd>

        <dt>Comprobante</dt>
        <dd>Resumen imprimible de una reserva pagada, con el localizador y el total.</dd>

        <dt>CEO de aerolínea</dt>
        <dd>Cuenta de la persona que administra los vuelos y las promociones de una aerolínea adherida.</dd>
    </dl>
</section>
